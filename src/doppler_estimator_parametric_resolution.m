%% Local function

function iqSignal = readIQSegment( ...
    fid, ...
    startComplexSample, ...
    numberOfComplexSamples, ...
    bytesPerScalar, ...
    readType)

    if numberOfComplexSamples <= 0

        iqSignal = complex(zeros(0, 1));
        return;
    end

    byteOffset = ...
        startComplexSample * ...
        2 * bytesPerScalar;

    seekStatus = fseek( ...
        fid, ...
        byteOffset, ...
        'bof');

    if seekStatus ~= 0
        error('Could not seek to the requested file position.');
    end

    rawData = fread( ...
        fid, ...
        [2, numberOfComplexSamples], ...
        readType);

    if isempty(rawData)

        iqSignal = complex(zeros(0, 1));
        return;
    end

    iqSignal = ...
        rawData(1, :).'+ ...
        1i * rawData(2, :).';
end

                'Power spectrum', ...
                'Raw FFT-bin estimate', ...
                'Sub-bin interpolated estimate', ...
                'Location', ...
                'best');

            carrierPeakExampleShown = true;

            drawnow;
        end
    end

    %% Save frame-center time

    timeVector(frameIndex) = ...
        (coreStartSample + ...
        (coreSampleCount - 1) / 2) / Fs;

    if mod(frameIndex, 100) == 0 || ...
            frameIndex == numberOfFrames

        fprintf( ...
            'Processed frame %d of %d\n', ...
            frameIndex, ...
            numberOfFrames);
    end
end

